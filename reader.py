# =============================================================================
# RSSリーダー（設定ファイル対応版）
# =============================================================================
#
# このプログラムの目的:
#   config.yaml に書いた複数のRSSフィードをまとめて取得し、画面に表示する
#
# 使い方:
#   1. まず、必要なライブラリをインストールします:
#      py -m pip install -r requirements.txt
#
#   2. config.yaml を開いて、RSSフィードのURLを書きます
#
#   3. このファイルを実行します:
#      py reader.py
#
#   4. 画面に各フィードの記事一覧が表示されたら成功です！
#
# =============================================================================

# --- 外部ライブラリの読み込み ---
# feedparser: RSSフィード（XML形式のデータ）を読み込むライブラリ
import feedparser

# yaml: YAML形式の設定ファイルを読み込むライブラリ
# Pythonには標準では入っていないので、pipでインストールする必要があります
import yaml


# --- メインの処理 ---
def main():
    """
    このプログラムのメイン処理。
    1. 設定ファイルを読み込む
    2. 各フィードを順番に取得する
    3. 画面に表示する
    """

    # =========================================================================
    # 1. 設定ファイルを読み込む
    # =========================================================================

    # open() はファイルを開くPythonの標準関数です
    # "r" = 読み込みモード、encoding="utf-8" = 日本語が壊れないようにする
    with open("config.yaml", "r", encoding="utf-8") as f:
        # yaml.safe_load() はYAMLファイルを辞書（dict）に変換してくれます
        # safe_load は「安全に読み込む」関数で、悪意あるコードが書かれていても実行しません
        config = yaml.safe_load(f)

    # config は以下のような辞書になっています:
    # {
    #     "feeds": [
    #         {"label": "Gigazine", "url": "https://..."},
    #         {"label": "Publickey", "url": "https://..."},
    #         ...
    #     ]
    # }
    feeds = config["feeds"]

    # =========================================================================
    # 2. 見出しを表示
    # =========================================================================

    print("=" * 60)
    print("  RSSリーダー")
    print("=" * 60)
    print()
    print(f"読み込むフィード数: {len(feeds)}件")
    print("-" * 60)
    print()

    # =========================================================================
    # 3. 各フィードを順番に取得して表示
    # =========================================================================

    # 全フィード合計の記事数を数える変数
    total_count = 0

    # feeds の中身を1つずつ取り出して処理します
    # feed には {"label": "Gigazine", "url": "https://..."} のような辞書が入っています
    for feed in feeds:
        # 辞書から値を取り出すには ["キー名"] を使います
        label = feed["label"]
        url = feed["url"]

        # --- 1つのフィードを取得 ---
        # feedparser.parse() にURLを渡すと、自動的にHTTPリクエストを送って
        # XMLを解析し、Pythonで扱いやすいデータ構造に変換してくれます
        parsed = feedparser.parse(url)

        # --- フィード名を表示 ---
        # f"..." は f-string（エフストリング）と呼ばれる記法で、
        # 波括弧 {変数} の中にPythonの変数を直接埋め込めます
        print(f"【{label}】")

        # --- 各記事を表示 ---
        # parsed.entries は記事のリストです
        # [:5] は「先頭から5つだけ」取り出すスライスという記法です
        for i, entry in enumerate(parsed.entries[:5], start=1):
            title = entry.get("title", "タイトルなし")
            link = entry.get("link", "")

            print(f"  {i}. {title}")
            print(f"     {link}")
            print()

        # 件数を加算
        count = len(parsed.entries[:5])
        total_count += count

        # このフィードの件数を表示
        print(f"  → {count}件")
        print()
        print("-" * 60)
        print()

    # =========================================================================
    # 4. 合計を表示
    # =========================================================================

    print("=" * 60)
    print(f"合計 {total_count}件の記事を取得しました")
    print("=" * 60)


# --- プログラムのエントリポイント ---
# このおまじないは、「このファイルが直接実行されたときだけ main() を動かす」
# という意味です。他のファイルから import されたときには自動実行されません。
if __name__ == "__main__":
    main()
