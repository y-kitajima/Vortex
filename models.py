# =============================================================================
# models.py ― このアプリで扱う「データの箱」の定義を集めたファイル
# =============================================================================
#
# 【dataclass（データクラス）とは】
#   これまで記事は dict（辞書）で扱っていました:
#       {"title": "...", "link": "..."}
#   dict の弱点は「キーの打ち間違い」をPythonが検出できないことです。
#   例えば記事["tittle"]（lが足りない）と書いたとき、dictは黙って
#   KeyError や None を返して、原因調査が遠回りになります。
#
#   dataclass は「この箱にはこの名前の中身だけが入る」という設計図を
#   クラスで宣言する仕組みで、打ち間違いは即 AttributeError で
#   「そこ、存在しません」とはっきり教えてくれます。
#   さらに「何が入る箱か」がファイルを見た人に伝わる、文档にもなる、
#   エディタの補完が効く、という利点があります。
#
# 【frozen=True】
#   「箱の中身は作り直さない」という約束です。
#   article.title = "書き換え" とすると実行時エラーになります。
#   設定や記事は「作ったら読み取り専用で扱う」ほうが
#   「途中で誰かが勝手に変えた」系のバグが構造的に発生しなくなります。
#   必要の無い可変性は禁止する、という設計の考え方の表現です。
#
# =============================================================================

# dataclass: 上記の「箱の設計図」を1行で自動生成してくれる decorator（飾り）
from dataclasses import dataclass


@dataclass(frozen=True)
class Topic:
    """1つのトピック（RSSのまとまり）を表す箱。config.yaml の topics 節から作られる。"""

    key: str
    """内部ID。YAMLのキー名そのもの（例: "tech_news"）。表示には使わない安定した名前"""

    label: str
    """表示名。Discordの見出しになる（例: "テックニュース"）"""

    feeds: list[str]
    """このトピックに所属するRSS URLのリスト"""


@dataclass(frozen=True)
class Article:
    """RSSから正規化した記事1件を表す箱。"""

    topic_key: str
    """どこのトピックから来た記事かの内部ID（Topic.keyと対応）"""

    topic_label: str
    """どこのトピックから来た記事かの表示名（embedの見出しに使う）"""

    title: str
    """記事のタイトル（サイトが公開している見出しテキスト）"""

    link: str
    """記事のURL。既読管理のキーかつDiscordに出すリンク"""

    source: str
    """出典のドメイン（例: "gigazine.net"）。同じトピックに複数サイトが
    混ざったとき「どのサイトの記事か」を見分けるために持たせます"""

    published: float | None
    """公開時刻のUNIX秒。RSSに日付が無い場合は None
    （Noneは後段の窓フィルタで「新しめ」として扱われる）"""
